export const AsciiAnimation: FC<AsciiAnimationProps> = ({ className }) => {
  const [frame, setFrame] = useState(0);

  useEffect(() => {
    const interval = setInterval(() => {
      setFrame((prev) => (prev + 1) % frames.length);
    }, 500);
    return () => clearInterval(interval);
  }, []);

  return (
    <pre
      className={`text-xs leading-tight text-white/30 font-mono whitespace-pre ${className}`}
      key={frame}
    >
      {frames[frame]}
    </pre>
  );
};